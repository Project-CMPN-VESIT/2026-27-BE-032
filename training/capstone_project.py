# =========================================================
# 1. IMPORT LIBRARIES
# =========================================================

import numpy as np
import matplotlib.pyplot as plt

import tensorflow as tf
from tensorflow.keras.layers import Input, Conv2D, MaxPooling2D, UpSampling2D
from tensorflow.keras.models import Model
from tensorflow.keras.optimizers import Adam



# =========================================================
# 3. DATASET LOADING
# =========================================================

IMG_SIZE = (128, 128)
BATCH_SIZE = 32

import os

BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATASET_PATH = os.path.join(BASE_DIR, "dataset", "DFU")

datagen = ImageDataGenerator(
    rescale=1./255,
    validation_split=0.2
)

train_data = datagen.flow_from_directory(
    DATASET_PATH,
    target_size=IMG_SIZE,
    batch_size=BATCH_SIZE,
    class_mode='input',
    subset='training'
)

val_data = datagen.flow_from_directory(
    DATASET_PATH,
    target_size=IMG_SIZE,
    batch_size=BATCH_SIZE,
    class_mode='input',
    subset='validation'
)


# =========================================================
# 4. ADD NOISE FUNCTION
# =========================================================

def add_noise(images):
    noise = np.random.normal(0, 0.05, images.shape)
    noisy_images = images + noise
    return np.clip(noisy_images, 0., 1.)


# =========================================================
# 5. BUILD AUTOENCODER MODEL
# =========================================================

input_img = Input(shape=(128, 128, 3))

# Encoder
x = Conv2D(32, (3,3), activation='relu', padding='same')(input_img)
x = MaxPooling2D((2,2), padding='same')(x)

x = Conv2D(64, (3,3), activation='relu', padding='same')(x)
x = MaxPooling2D((2,2), padding='same')(x)

# Bottleneck
x = Conv2D(128, (3,3), activation='relu', padding='same')(x)

# Decoder
x = Conv2D(64, (3,3), activation='relu', padding='same')(x)
x = UpSampling2D((2,2))(x)

x = Conv2D(32, (3,3), activation='relu', padding='same')(x)
x = UpSampling2D((2,2))(x)

output = Conv2D(3, (3,3), activation='sigmoid', padding='same')(x)

autoencoder = Model(input_img, output)

autoencoder.compile(
    optimizer=Adam(learning_rate=0.001),
    loss='mse',
    metrics=['accuracy']
)

autoencoder.summary()


# =========================================================
# 6. TRAIN MODEL (NOISY → CLEAN)
# =========================================================

EPOCHS = 10

train_generator = ((add_noise(x), x) for x, _ in train_data)
val_generator = ((add_noise(x), x) for x, _ in val_data)

history = autoencoder.fit(
    train_generator,
    steps_per_epoch=train_data.samples // BATCH_SIZE,
    epochs=EPOCHS,
    validation_data=val_generator,
    validation_steps=val_data.samples // BATCH_SIZE
)


# =========================================================
# 7. PERFORMANCE GRAPHS
# =========================================================

plt.figure(figsize=(12,5))

plt.subplot(1,2,1)
plt.plot(history.history['loss'], label='Training Loss')
plt.plot(history.history['val_loss'], label='Validation Loss')
plt.title("Loss Curve")
plt.legend()

plt.subplot(1,2,2)
plt.plot(history.history['accuracy'], label='Training Accuracy')
plt.plot(history.history['val_accuracy'], label='Validation Accuracy')
plt.title("Accuracy Curve")
plt.legend()

plt.show()


# =========================================================
# 8. VISUALIZATION (RESULTS)
# =========================================================

sample = next(train_data)[0]

noisy = add_noise(sample)
reconstructed = autoencoder.predict(noisy)

n = 5
plt.figure(figsize=(18,10))

plt.suptitle("Denoising Autoencoder Results", fontsize=18)

for i in range(n):

    # Original
    plt.subplot(3, n, i+1)
    plt.imshow(sample[i])
    if i == 2:
        plt.title("Original Images")
    plt.axis("off")

    # Noisy
    plt.subplot(3, n, i+n+1)
    plt.imshow(noisy[i])
    if i == 2:
        plt.title("Noisy Input Images")
    plt.axis("off")

    # Reconstructed
    plt.subplot(3, n, i+2*n+1)
    plt.imshow(reconstructed[i])
    if i == 2:
        plt.title("Reconstructed Images")
    plt.axis("off")

plt.tight_layout()
plt.show()

autoencoder.save("foot_autoencoder.keras")

"""This Dataset uses a Denoising Autoencoder to remove noise from DFU images.

- Encoder extracts features and compresses the image.
- Bottleneck stores essential information.
- Decoder reconstructs the image.

Noise is artificially added to input images, and the model learns to recover clean images.

Activation Functions:
- ReLU: Used in hidden layers
- Sigmoid: Used in output layer

Optimizer:
- Adam

Loss Function:
- Mean Squared Error (MSE)

Output:
- Original Image
- Noisy Image
- Reconstructed Image

The model successfully removes noise, though slight blurring may occur due to compression.

The DFU (Diabetic Foot Ulcer) dataset contains clear and high-quality images, so the use of a denoising autoencoder is not essential. A denoising autoencoder works by adding artificial noise to input images and learning to reconstruct the original clean images. In this case, Gaussian noise is added using np.random.normal, which randomly disturbs pixel values and alters image intensity.

As a result, the noisy images appear slightly blurred or distorted, and during reconstruction, the model may lose some fine details due to compression in the bottleneck layer. This leads to smoother but slightly blurred output images compared to the original. Therefore, this approach is not ideal for this dataset where images are already clean.

**2. ResNet 50 For DFU (Diabetic Foot Ulcer) Dataset**
"""

# =========================================================
# IMPORTS
# =========================================================
import numpy as np
import matplotlib.pyplot as plt

import tensorflow as tf
# pyrefly: ignore [missing-import]
from tensorflow.keras.preprocessing.image import ImageDataGenerator
# pyrefly: ignore [missing-import]
from tensorflow.keras.applications import ResNet50
from tensorflow.keras.layers import Dense, GlobalAveragePooling2D, Dropout
from tensorflow.keras.models import Model
from tensorflow.keras.optimizers import Adam


# =========================================================
# DATA GENERATOR (WITH AUGMENTATION)
# =========================================================
IMG_SIZE = (224, 224)
BATCH_SIZE = 16

datagen = ImageDataGenerator(
    rescale=1./255,
    validation_split=0.2,
    rotation_range=15,
    horizontal_flip=True,
    zoom_range=0.1
)

train_data = datagen.flow_from_directory(
    DATASET_PATH,
    target_size=IMG_SIZE,
    batch_size=BATCH_SIZE,
    class_mode='categorical',
    subset='training'
)

val_data = datagen.flow_from_directory(
    DATASET_PATH,
    target_size=IMG_SIZE,
    batch_size=BATCH_SIZE,
    class_mode='categorical',
    subset='validation'
)

# =========================================================
# RESNET50 BASE
# =========================================================
base_model = ResNet50(
    weights='imagenet',
    include_top=False,
    input_shape=(224, 224, 3)
)

# Freeze most layers (faster training)
for layer in base_model.layers[:-20]:
    layer.trainable = False

# =========================================================
# CUSTOM HEAD
# =========================================================
x = base_model.output
x = GlobalAveragePooling2D()(x)
x = Dense(128, activation='relu')(x)
x = Dropout(0.5)(x)
output = Dense(4, activation='softmax')(x)

model = Model(inputs=base_model.input, outputs=output)

# =========================================================
# COMPILE
# =========================================================
model.compile(
    optimizer=Adam(learning_rate=0.0001),
    loss='categorical_crossentropy',
    metrics=['accuracy']
)

# =========================================================
# TRAIN
# =========================================================
EPOCHS = 8

history = model.fit(
    train_data,
    epochs=EPOCHS,
    validation_data=val_data
)

# =========================================================
# SAVE
# =========================================================
model.save("dfu_resnet50_fast.keras")

# =========================================================
# PERFORMANCE GRAPHS
# =========================================================

plt.figure(figsize=(12,5))

# Loss Graph
plt.subplot(1,2,1)
plt.plot(history.history['loss'], label='Training Loss')
plt.plot(history.history['val_loss'], label='Validation Loss')
plt.title("Loss Curve")
plt.xlabel("Epochs")
plt.ylabel("Loss")
plt.legend()

# Accuracy Graph
plt.subplot(1,2,2)
plt.plot(history.history['accuracy'], label='Training Accuracy')
plt.plot(history.history['val_accuracy'], label='Validation Accuracy')
plt.title("Accuracy Curve")
plt.xlabel("Epochs")
plt.ylabel("Accuracy")
plt.legend()

plt.show()

# =========================================================
# SAMPLE IMAGES
# =========================================================

images, labels = next(val_data)
